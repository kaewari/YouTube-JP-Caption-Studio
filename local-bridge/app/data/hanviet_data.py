_KANJI_PATTERN = re.compile(r'[㐀-䶿一-鿿豈-﫿]')


def get_hanviet_reading(text: str) -> str:
    """Extract kanji characters from text and return capitalized Sino-Vietnamese reading.

    Args:
        text: Input Japanese text containing Kanji and/or Kana.

    Returns:
        Space-separated Hán-Việt reading string (e.g. 'Ước Thúc'), or empty string if no Kanji.
    """
    if not text:
        return ""
    readings: list[str] = []
    for ch in text:
        if _KANJI_PATTERN.match(ch):
            hv = KANJI_HANVIET_TABLE.get(ch)
            if hv:
                readings.append(hv)
    return " ".join(readings)
